# One-time local metadata DB password enrollment for Windows DBPulse.exe.
# Requires existing .env and a built app-image. SQL Server DPAPI blobs are not touched.
param([string]$ExePath, [switch]$ReplaceExisting)

$ErrorActionPreference='Stop'
if ($env:OS -ne 'Windows_NT') { throw 'Windows user DPAPI enrollment requires Windows.' }
$root=(Resolve-Path (Join-Path $PSScriptRoot '..')).Path
Set-Location $root
$envPath=Join-Path $root '.env'
if (-not (Test-Path -LiteralPath $envPath)) {
    throw 'Existing DBPulse .env is required for one-time metadata setup.'
}

# Discover latest unpacked preview executable, unless one was supplied.
if ([string]::IsNullOrWhiteSpace($ExePath)) {
    $previewDir=Join-Path (Join-Path (Join-Path $root 'backend') 'target') 'windows-previews'
    $exe=Get-ChildItem -Path $previewDir -Filter DBPulse.exe -Recurse -File -ErrorAction SilentlyContinue |
        Sort-Object LastWriteTimeUtc -Descending | Select-Object -First 1
    if ($null -eq $exe) { throw 'No DBPulse.exe preview found; build the app-image first.' }
    $ExePath=$exe.FullName
}
$ExePath=(Resolve-Path -LiteralPath $ExePath -ErrorAction Stop).Path
if ([IO.Path]::GetFileName($ExePath) -ne 'DBPulse.exe') {
    throw 'Expected a DBPulse.exe generated by the Windows app-image build.'
}
if (-not (Test-Path (Join-Path (Split-Path $ExePath -Parent) 'runtime'))) {
    throw 'Selected app-image is incomplete: Java runtime folder is missing.'
}

$protectedDir=Join-Path $env:LOCALAPPDATA 'DBPulse\desktop'
$protectedFile=Join-Path $protectedDir 'metadata.dpapi'
if ((Test-Path -LiteralPath $protectedFile) -and -not $ReplaceExisting) {
    throw 'Desktop metadata credential is already enrolled. Pass -ReplaceExisting ONLY to explicitly change it.'
}

function Read-Key {
    param([string]$Name)
    # Parse only the named .env variable; never execute the entire file.
    foreach ($line in [IO.File]::ReadAllLines($envPath)) {
        if ($line -match ('^\s*'+[regex]::Escape($Name)+'\s*=(.*)$')) {
            $value=$Matches[1].Trim()
            if ($value.Length -ge 2 -and
                (($value.StartsWith('"') -and $value.EndsWith('"')) -or
                 ($value.StartsWith("'") -and $value.EndsWith("'")))) {
                $value=$value.Substring(1,$value.Length-2)
            }
            return $value
        }
    }
    return ''
}

$metaPassword=Read-Key 'DBPULSE_POSTGRES_PASSWORD'
if ([string]::IsNullOrWhiteSpace($metaPassword)) {
    throw 'DBPULSE_POSTGRES_PASSWORD was not found in .env.'
}
$localTls=Read-Key 'DBPULSE_LOCAL_TRUST_SELF_SIGNED'
if ($localTls -notin @('true','false','')) {
    throw 'DBPULSE_LOCAL_TRUST_SELF_SIGNED must be true or false.'
}

# Supply metadata DB password to the app-image enrollment process once.
# The executable uses current-Windows-user DPAPI; no plaintext file is written.
# Clear the environment variable in this shell even when enrollment fails.
try {
    $env:DBPULSE_META_PASSWORD=$metaPassword
    $env:DBPULSE_LOCAL_TRUST_SELF_SIGNED= if ($localTls -eq 'true') { 'true' } else { 'false' }
    & $ExePath --desktop-provision
    if ($LASTEXITCODE -ne 0) { throw 'Windows DPAPI enrollment failed.' }
    & $ExePath --desktop-check
    if ($LASTEXITCODE -ne 0) { throw 'Encrypted metadata credential validation failed.' }
} finally {
    Remove-Item Env:DBPULSE_META_PASSWORD -ErrorAction SilentlyContinue
    Remove-Item Env:DBPULSE_LOCAL_TRUST_SELF_SIGNED -ErrorAction SilentlyContinue
    Remove-Variable metaPassword -ErrorAction SilentlyContinue
}

Write-Host 'DBPulse.exe metadata setup complete. Current Windows user DPAPI has been verified.'
Write-Host 'You may now double-click DBPulse.exe when Docker PostgreSQL is running.'
Write-Host 'No SQL Server password or prior DBPulse metrics were modified.'
